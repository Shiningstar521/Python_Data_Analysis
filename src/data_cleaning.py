"""
============================================================
项目名称：Online Retail II 数据分析项目
模块名称：data_cleaning.py
模块功能：原始零售交易数据清洗与预处理
============================================================

一、模块说明
本模块主要负责 Online Retail II 原始数据集的清洗与预处理，
解决数据缺失、重复记录、异常数据以及数据格式不统一等问题，
为后续的数据分析和可视化提供可靠的数据基础。

二、清洗目标
1. 统一字段名称和数据类型。
2. 检查并合理处理缺失值。
3. 检查并处理无效重复记录。
4. 识别负数量、异常单价和取消订单等特殊业务数据。
5. 构建清洗后的完整数据集和销售分析数据集。
6. 保存清洗结果及数据质量报告。

三、清洗原则
1. 保留原始数据，不直接修改原始文件。
2. 结合零售业务含义判断数据是否有效，不盲目删除异常记录。
3. 保留必要的业务信息，确保数据处理过程可追溯。
4. 根据不同分析需求构建不同的数据集。
5. 重要清洗操作应进行记录，保证代码可复现。

四、具体清洗流程

1. 数据格式标准化
   - 统一字段名称，去除多余空格。
   - 将 InvoiceDate 转换为日期时间类型。
   - 将 Quantity、Price、Customer ID 转换为数值类型。
   - 清理字符串字段中的多余空格。
   - 检查字段类型是否符合预期。

2. 缺失值处理
   - 使用 isnull() 检查各字段缺失情况。
   - 统计缺失数量及缺失比例。
   - 根据字段业务含义决定保留、删除或填充。
   - Customer ID 缺失记录可保留，但不参与客户身份相关分析。
   - 关键交易字段缺失时，根据实际情况判断是否保留。
   - 不随意使用 0 填充 Quantity 和 Price。

3. 重复值处理
   - 使用 duplicated() 检查完全重复记录。
   - 统计重复记录数量。
   - 检查跨工作表数据是否存在重复。
   - 确认无效重复记录后再进行删除。
   - 不仅根据 Invoice 和 StockCode 判断重复，
     避免误删同一订单中的有效商品记录。

4. 业务异常数据处理
   - 识别 Quantity < 0 的记录，可能代表退货或冲销。
   - 识别 Price <= 0 的记录，进一步核查赠品或异常交易。
   - 标记 Invoice 以 C 开头的记录，识别可能的取消订单。
   - 使用 IQR（四分位距）方法识别极端值。
   - 对具有业务意义的特殊记录进行保留和标记，
     不直接删除。

5. 构建分析数据集
   - cleaned_data：清洗后的完整数据集，保留具有分析价值的
     正常交易、退货、取消订单及其他特殊交易记录。
   - sales_data：根据正常销售分析口径筛选数据，
     初步筛选条件为 Quantity > 0、Price > 0，
     且 InvoiceDate 有效。
   - 新增 Sales 字段，计算方式：
     Sales = Quantity * Price

6. 数据质量复检
   - 再次检查缺失值和重复记录。
   - 检查数值字段的数据类型及有效性。
   - 检查销售分析数据集是否满足筛选条件。
   - 检查 Sales 字段是否存在异常值。
   - 对比清洗前后的数据规模。

7. 保存清洗结果
   - data/processed/cleaned_data.csv
   - data/processed/sales_data.csv
   - data/processed/cleaning_report.csv

五、模块预期输出
1. cleaned_data：清洗后的完整数据集。
2. sales_data：用于正常销售分析的数据集。
3. cleaning_report：数据清洗及质量检查报告。

六、注意事项
1. 退货、取消订单和特殊价格记录应结合业务含义处理。
2. 销售分析数据集不等于完整交易数据集。
3. 清洗过程中应尽可能保留原始业务信息。
4. 所有清洗规则应根据实际数据检查结果进行调整。

============================================================
"""
